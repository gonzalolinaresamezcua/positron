    <h1>Privacidad</h1>
    <p>POSITROM trata el correo, el nombre y los mensajes del chat para prestar el servicio gratuito autoalojado. La dirección IP se almacena solo como hash HMAC, no en claro.</p>
    <p>Las claves de API OpenAI viven en el servidor (<code>.env</code>) y no se publican en el repositorio. Quien despliega la instancia es responsable de su clave.</p>
    <p>Puedes pedir la baja de la cuenta escribiendo a la administración del sitio.</p>
