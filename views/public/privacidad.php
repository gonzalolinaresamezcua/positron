    <h1>Privacidad</h1>
    <p>POSITRON trata el correo, el nombre y los mensajes del chat para prestar la suscripción. La dirección IP se almacena solo como hash HMAC, no en claro.</p>
    <p>Los pagos los procesa Mollie. Las claves de API viven en el servidor (<code>.env</code>) y no se publican en el repositorio.</p>
    <p>Puedes pedir la baja de la cuenta escribiendo a la administración del sitio.</p>
